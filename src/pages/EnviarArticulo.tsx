function htmlToPlainText(html: string): string {
  if (!html) return "";

  if (typeof DOMParser === "undefined") {
    return html
      .replace(/<[^>]*>/g, " ")
      .replace(/\s+/g, " ")
      .trim();
  }

  const documentFragment = new DOMParser().parseFromString(
    html,
    "text/html",
  );

  documentFragment
    .querySelectorAll("script, style, noscript, template")
    .forEach((element) => element.remove());

  return (documentFragment.body.textContent ?? "")
    .replace(/\u00a0/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function countPlainCharacters(value: string): number {
  return Array.from(value.trim()).length;
}

function countVisibleWords(html: string): number {
  const text = htmlToPlainText(html);
  return text ? text.split(/\s+/).filter(Boolean).length : 0;
}

function createPendingImageId() {
  if (typeof crypto !== "undefined" && "randomUUID" in crypto) {
    return `article-${crypto.randomUUID()}`;
  }

  return `article-${Date.now()}-${Math.random()
    .toString(36)
    .slice(2, 10)}`;
}

function extractUsedPendingImageIds(html: string): string[] {
  if (!html || typeof DOMParser === "undefined") return [];

  const documentFragment = new DOMParser().parseFromString(
    html,
    "text/html",
  );

  return Array.from(
    documentFragment.querySelectorAll(
      "img[data-pending-image-id]",
    ),
  )
    .map(
      (image) =>
        image.getAttribute("data-pending-image-id") ?? "",
    )
    .filter(Boolean);
}

const DRAFT_STORAGE_KEY = "wff_voces_draft_v1";
